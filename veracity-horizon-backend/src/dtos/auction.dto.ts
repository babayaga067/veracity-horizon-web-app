import { z } from "zod";

export const CreateAuctionSchema = z.object({
  title: z.string().min(3, "Title must be at least 3 characters"),
  description: z.string().min(10, "Description must be at least 10 characters"),
  startingPrice: z.number().min(1, "Starting price must be at least 1"),
  category: z.enum([
    "Art",
    "Electronics",
    "Vehicles",
    "Collectibles",
    "Fashion",
    "Real Estate",
    "Textiles",
    "Jewelry",
    "Antiques",
    "Food & Spices",
    "Handicrafts",
    "Musical Instruments",
    "Books & Manuscripts",
    "Furniture",
    "Sports & Gear",
    "Home & Living",
    "Industrial Equipment",
    "Luxury Goods",
    "Agriculture & Livestock",
    "Tools & Hardware",
    "Ceramics & Pottery",
    "Carpets & Rugs",
    "Coins & Currency",
    "Watches & Timepieces",
    "Photography",
    "Sculptures",
    "Paintings",
    "Textbooks & Academic",
    "Outdoor & Adventure",
    "Health & Wellness",
    "Office Supplies",
    "Children & Toys",
    "Cultural Heritage",
    "Religious Items",
    "Digital Assets",
  ]),
  endsAt: z.string().optional(),
  imageUrls: z.array(z.string()).optional(),
  status: z.enum(["upcoming", "active", "closed", "open"]).optional(),
  isFeatured: z.boolean().optional(),
});

export const ListAuctionsQuerySchema = z.object({
  page: z.coerce.number().min(1).optional(),
  limit: z.coerce.number().min(1).max(100).optional(),
  search: z.string().optional(),
  status: z.string().optional(),
  category: z.string().optional(),
  minPrice: z.coerce.number().min(0).optional(),
  maxPrice: z.coerce.number().min(0).optional(),
  sortBy: z.enum(["endsAt", "startingPrice", "currentBid", "createdAt"]).optional(),
  sortOrder: z.enum(["asc", "desc"]).optional(),
});

export type CreateAuctionDTO = z.infer<typeof CreateAuctionSchema>;
export type ListAuctionsQueryDTO = z.infer<typeof ListAuctionsQuerySchema>;
